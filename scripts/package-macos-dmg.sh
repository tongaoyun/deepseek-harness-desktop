#!/bin/bash
set -euo pipefail

if [[ "$(uname -s)" != "Darwin" ]]; then
  echo "macOS packaging must run on macOS." >&2
  exit 1
fi

script_dir="$(cd "$(dirname "$0")" && pwd)"
repository="$(cd "$script_dir/.." && pwd)"
version="$(node -p "require('$repository/package.json').version")"
source "$script_dir/macos-build-env.sh"
macos_check_execution

app="$target_dir/release/bundle/macos/小胤.app"
dmg="$target_dir/release/bundle/dmg/小胤_${version}_${artifact_arch}.dmg"
[[ -d "$app" ]] || { echo "Built application is missing: $app" >&2; exit 1; }

# Local/internal builds use an ad-hoc deep signature. Public distribution still
# requires a Developer ID certificate and Apple notarization.
/usr/bin/codesign --force --deep --sign - "$app"
/usr/bin/codesign --verify --deep --strict "$app"

# Repack after the final deep signature so updates and DMGs contain the same app.
# The archive generated by `tauri build` predates this signature and must not ship.
if [[ -z "${TAURI_SIGNING_PRIVATE_KEY-}" && -z "${TAURI_SIGNING_PRIVATE_KEY_PATH-}" ]]; then
  echo "A Tauri signing key is required for the final macOS updater archive." >&2
  exit 1
fi
/usr/bin/tar -czf "$app.tar.gz" -C "$(dirname "$app")" "$(basename "$app")"
gzip -t "$app.tar.gz"
pnpm --dir "$repository" exec tauri signer sign "$app.tar.gz"

stage="$(mktemp -d)"
trap 'rm -rf -- "$stage"' EXIT
ditto "$app" "$stage/小胤.app"
ln -s /Applications "$stage/Applications"
mkdir -p "$(dirname "$dmg")"
hdiutil create -volname "小胤" -srcfolder "$stage" -ov -format UDZO "$dmg"

echo "macOS application: $app"
echo "macOS disk image: $dmg"
shasum -a 256 "$dmg"
